"""Embeds the approved 5P-8P art (tags_5p8p_1x.png, labels_5p8p_1x.png, frame_5p..8p_1x.png) in the
game as GX RGBA8 textures laid out like the game's own 1P-4P bitmaps, so the menu can show them with the
original sprites' banks and patterns (src/REL/mentDll/main.c, Ment8ArtAnim):
- tags: the 200x64 cursor-tag atlas layout (cells 40 wide: 5P-8P where the game has 1P-4P; the COM
  column stays empty), star bank on top, dome bank below;
- labels: the 32x72 small seat-label layout (four 18-pixel rows: 5P-8P where the game has 1P-4P);
- frames: the 96x192 portrait frame, one per seat.
    python3 inc.py <tools/tags8 dir> <out .inc>
    python3 inc.py <tools/tags8 dir> <out .inc> --tags-only <array name>
(the second form writes only the tag atlas, for the board pause menu's controller page:
 src/game/board/tags5to8_pause.inc, array pause8TagTex)
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen import read_png

def rgba8_tiles(rows):
    h = len(rows); w = len(rows[0]); assert w % 4 == 0 and h % 4 == 0
    out = bytearray()
    for ty in range(0, h, 4):
        for tx in range(0, w, 4):
            px = [rows[ty + y][tx + x] for y in range(4) for x in range(4)]
            for r, g, b, a in px: out += bytes((a, r))
            for r, g, b, a in px: out += bytes((g, b))
    return bytes(out)

def emit(f, name, w, h, rows, note):
    data = rgba8_tiles(rows)
    f.write('/* %s (%dx%d), GX RGBA8 tiles. */\nstatic const u8 %s[%d] = {\n' % (note, w, h, name, len(data)))
    for i in range(0, len(data), 24):
        f.write('    ' + ', '.join('0x%02x' % b for b in data[i:i + 24]) + ',\n')
    f.write('};\n')

def main(d, out, tags_only=None):
    _, _, tags = read_png(os.path.join(d, 'tags_5p8p_1x.png'))
    _, _, labels = read_png(os.path.join(d, 'labels_5p8p_1x.png'))
    atlas = [row + [(0, 0, 0, 0)] * 40 for row in tags]
    if tags_only:
        with open(out, 'w') as f:
            f.write('/* 5P-8P cursor tags for the board pause menu (approved 2026-10-16; same data as ment8TagTex in\n'
                    ' * src/REL/mentDll/tags5to8_tex.inc). Generated by tools/tags8/inc.py --tags-only; do not edit. */\n')
            emit(f, tags_only, 200, 64, atlas, '5P-8P cursor tags in the 1P-4P atlas layout')
        return
    with open(out, 'w') as f:
        f.write('/* 5P-8P seat art for the 8-player party, approved 2026-10-16 (5P orange, 6P pink, 7P silver,\n'
                ' * 8P brown, brightened). Generated by tools/tags8/inc.py from tools/tags8/*.png; do not edit. */\n')
        emit(f, 'ment8TagTex', 200, 64, atlas, '5P-8P cursor tags in the 1P-4P atlas layout')
        emit(f, 'ment8LabelTex', 32, 72, labels, '5P-8P small seat labels')
        for n in (5, 6, 7, 8):
            _, _, fr = read_png(os.path.join(d, 'frame_%dp_1x.png' % n))
            emit(f, 'ment8FrameTex%d' % n, 96, 192, fr, '%dP portrait frame' % n)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[4] if len(sys.argv) > 4 and sys.argv[3] == '--tags-only' else None)
